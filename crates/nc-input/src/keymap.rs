#[cfg(windows)]
pub(crate) fn hid_from_windows(virtual_key: u32, scan_code: u32, extended: bool) -> Option<u32> {
    if virtual_key == 0x13 {
        return Some(0x48);
    }
    if virtual_key == 0x2C {
        return Some(0x46);
    }

    if let Ok(scan_code) = u16::try_from(scan_code) {
        if scan_code != 0 {
            if let Some(entry) = WINDOWS_KEYS
                .iter()
                .find(|entry| entry.key.scan_code == scan_code && entry.key.extended == extended)
            {
                return Some(entry.hid);
            }
        }
    }

    let virtual_key = u16::try_from(virtual_key).ok()?;
    WINDOWS_KEYS
        .iter()
        .find(|entry| entry.key.virtual_key == virtual_key)
        .map(|entry| entry.hid)
}

#[cfg(windows)]
pub(crate) fn windows_from_hid(hid: u32) -> Option<WindowsKey> {
    WINDOWS_KEYS
        .iter()
        .find(|entry| entry.hid == hid)
        .map(|entry| entry.key)
}

#[cfg(target_os = "macos")]
pub(crate) fn hid_from_macos(key_code: u32) -> Option<u32> {
    let key_code = u16::try_from(key_code).ok()?;
    MACOS_KEYS
        .iter()
        .find(|entry| entry.key_code == key_code)
        .map(|entry| entry.hid)
}

#[cfg(target_os = "macos")]
pub(crate) fn macos_from_hid(hid: u32) -> Option<u16> {
    MACOS_KEYS
        .iter()
        .find(|entry| entry.hid == hid)
        .map(|entry| entry.key_code)
}

